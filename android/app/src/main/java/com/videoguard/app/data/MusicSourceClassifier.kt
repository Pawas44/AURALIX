package com.videoguard.app.data

import java.util.Locale

/**
 * Classifies YouTube upload sources into official music labels, verified artist channels,
 * topic channels, or third-party/fan uploaders.
 */
enum class ChannelSourceType {
    OFFICIAL_RECORD_LABEL,  // T-Series, Sony Music, Zee Music, Sonotek, Tips, Saregama, etc.
    OFFICIAL_ARTIST_CHANNEL,// Channel matches artist name, VEVO, or verified artist channel
    TOPIC_CHANNEL,          // "Artist - Topic", auto-generated studio release
    GENERAL_UPLOADER        // Fan channel, lyrics channel, third-party
}

object MusicSourceClassifier {

    // Comprehensive legitimate record labels & music distributors
    private val OFFICIAL_RECORD_LABELS = setOf(
        "sonotek", "sonotek music", "sonotek cassettes", "sonotek digital",
        "t-series", "tseries", "t-series regional", "t-series bhakti", "t-series apna punjab",
        "sony music", "sony music india", "sony music entertainment", "sony music south",
        "zee music company", "zee music", "zee cine", "zee music south",
        "tips official", "tips music", "tips industries", "tips",
        "saregama", "saregama music", "saregama hum bhojpuri",
        "yrf", "yash raj films", "yash raj",
        "eros now", "eros now music", "eros music",
        "universal music", "universal music india", "universal music group", "interscope", "republic records",
        "warner music", "warner music india", "warner records", "atlantic records",
        "believe music", "believe artist services", "believe",
        "speed records", "white hill music", "white hill studios",
        "geet mp3", "nav haryanvi", "gringo entertainments",
        "single track studios", "jass records", "saga hits",
        "times music", "times music india",
        "aditya music", "aditya music india", "lahari music", "think music", "think music india",
        "anand audio", "muzik247", "svf", "svf music", "red chillies entertainment",
        "shemaroo", "shemaroo filmi gaane", "wave music", "venus", "ultra bollywood",
        "pen music", "dharma productions", "voila! digi", "voila digi", "desimelodies",
        "desi music factory", "dm - desi melodies", "play dmf"
    )

    /**
     * Determines whether a channel is an official record label or distributor.
     */
    fun isOfficialRecordLabel(channelName: String): Boolean {
        val lower = channelName.lowercase(Locale.ROOT).trim()
        if (lower.isBlank()) return false
        return OFFICIAL_RECORD_LABELS.any { lower.contains(it) || it.contains(lower) }
    }

    /**
     * Determines whether a channel is an auto-generated Topic channel (high-fidelity studio audio).
     */
    fun isTopicChannel(channelName: String): Boolean {
        val lower = channelName.lowercase(Locale.ROOT).trim()
        return lower.endsWith("- topic") || lower.endsWith(" topic") || lower.contains("auto-generated by youtube")
    }

    /**
     * Determines whether a channel is the official channel of the expected artist.
     */
    fun isArtistOfficialChannel(channelName: String, expectedArtist: String): Boolean {
        if (channelName.isBlank() || expectedArtist.isBlank()) return false
        val cleanChan = channelName.lowercase(Locale.ROOT)
            .replace(Regex("(?i)\\b(official|vevo|channel|music|records|tv)\\b"), " ")
            .trim()
        val cleanArtist = expectedArtist.lowercase(Locale.ROOT)
            .replace(Regex("(?i)\\b(official|vevo|channel|music|records|tv)\\b"), " ")
            .trim()

        if (cleanChan == cleanArtist) return true
        if (cleanChan.contains(cleanArtist) || cleanArtist.contains(cleanChan)) {
            val minLen = minOf(cleanChan.length, cleanArtist.length).toFloat()
            val maxLen = maxOf(cleanChan.length, cleanArtist.length).toFloat()
            if (minLen / maxLen >= 0.70f) return true
        }
        return false
    }

    /**
     * Classifies the channel source type.
     */
    fun classifySource(channelName: String, expectedArtist: String): ChannelSourceType {
        if (isTopicChannel(channelName)) {
            return ChannelSourceType.TOPIC_CHANNEL
        }
        if (isArtistOfficialChannel(channelName, expectedArtist)) {
            return ChannelSourceType.OFFICIAL_ARTIST_CHANNEL
        }
        if (isOfficialRecordLabel(channelName)) {
            return ChannelSourceType.OFFICIAL_RECORD_LABEL
        }
        return ChannelSourceType.GENERAL_UPLOADER
    }

    /**
     * Computes the credibility/authenticity score bonus for this channel.
     */
    fun getSourceScoreBonus(channelName: String, expectedArtist: String): Int {
        return when (classifySource(channelName, expectedArtist)) {
            ChannelSourceType.TOPIC_CHANNEL -> 35 // Guaranteed studio audio
            ChannelSourceType.OFFICIAL_RECORD_LABEL -> 30 // Authentic label release (Sony, Sonotek, T-Series, etc.)
            ChannelSourceType.OFFICIAL_ARTIST_CHANNEL -> 28 // Artist's verified channel
            ChannelSourceType.GENERAL_UPLOADER -> {
                val lower = channelName.lowercase(Locale.ROOT)
                if (lower.contains("lyrics") || lower.contains("vibes") || lower.contains("status")) {
                    -15 // Fan / lyrics channel penalty when official sources are available
                } else {
                    0
                }
            }
        }
    }
}
